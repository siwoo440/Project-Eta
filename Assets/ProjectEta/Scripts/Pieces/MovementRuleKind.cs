namespace ProjectEta.Pieces // 기물 이동 규칙 데이터 타입을 모아두는 네임스페이스
{
    public enum MovementRuleKind // PieceDefinition이 조합할 수 있는 기본 이동 규칙의 종류
    {
        Step = 0, // 지정 방향으로 제한된 칸 수만큼 한 칸씩 진행하는 규칙
        Slide = 1, // 지정 방향으로 장애물이나 보드 끝까지 연속 이동하는 규칙
        Leap = 2, // 중간 칸을 무시하고 지정 상대 좌표로 바로 도약하는 규칙
        Conditional = 3, // 진영이나 런타임 상태에 따라 별도 계산이 필요한 조건부 규칙
        Rider = 4, // 동일한 도약 벡터를 같은 방향으로 반복하는 라이더 규칙
        Hopper = 5, // 첫 번째 기물을 발판으로 삼아 바로 뒤 한 칸에 착지하는 그래스호퍼 규칙
        Cannon = 6 // 직교 1칸 이동과 직교 장거리 원거리 공격을 분리하는 캐논 규칙
    }
}
